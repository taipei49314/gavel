"""Generate results/round-3/TABLES.md from the files the round-3 stage-1
papers already wrote (PREREG Addendum 4: tallies are generated by a script,
never written by hand).

    python -I -B tools/round3_report.py

Reads, per paper, results/round-3/<paper>/run-1/{RUN.json, report.json,
results.json, receipts.jsonl, verify.stdout.txt, ollama-load.txt} and, for K,
scoring/scoring.json; the operator checks in results/round-3/lock-check/;
the GitHub push events saved in results/round-3/push-events.json; and git for
the commits that added each record. It imports nothing from gavel and scores
nothing: a paper that ended INCOMPLETE has no score here, and no ground truth
is compared. Standard library only.
"""

import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R3 = ROOT / "results" / "round-3"
PAPERS = ["R", "K", "R-fast", "K-fast"]
OUT = R3 / "TABLES.md"

# Placement lines, as in results/round-3/lock-check/loadcheck.py.
PLACEMENT = [
    re.compile(r"cannot meet free memory target|will leave .* no changes needed"),
    re.compile(r"set ngl_per_device\[0\]\.\(n_layer, n_part, overflow_type\)="),
    re.compile(r"CUDA0 \(.*\): \d+ layers \(\d+ overflowing\)"),
    re.compile(r"offloaded \d+/\d+ layers to GPU"),
    re.compile(r"model buffer size"),
    re.compile(r"KV buffer size"),
]


def norm(line: str) -> str:
    line = re.sub(r"^time=\S+ ", "", line.rstrip("\r\n"))
    line = re.sub(r"--port \d+ ", "", line)
    line = re.sub(r"(\d+ layers \(\d+ overflowing\),\s+\d+ MiB used),\s+\d+ MiB free", r"\1", line)
    line = re.sub(r"need to reduce device memory by \d+ MiB", "need to reduce device memory by N MiB", line)
    return re.sub(r"will leave \d+ >=", "will leave N >=", line)


def placement(block):
    out = [norm(l) for l in block if any(p.search(l) for p in PLACEMENT)]
    sets = [l for l in out if "set ngl_per_device[0].(n_layer, n_part, overflow_type)=" in l]
    return tuple(l for l in out if l not in sets[:-1])


def git(*args) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True,
                          encoding="utf-8", check=True).stdout.strip()


def is_ancestor(a: str, b: str) -> bool:
    return subprocess.run(["git", "merge-base", "--is-ancestor", a, b], cwd=ROOT,
                          capture_output=True).returncode == 0


def added_in(path: Path) -> str:
    rel = path.relative_to(ROOT).as_posix()
    return git("log", "--diff-filter=A", "--format=%H", "-1", "--", rel)


EVENTS = json.loads((R3 / "push-events.json").read_text(encoding="utf-8"))
RUN_EVENTS = EVENTS["refs"]["refs/heads/round-3/run-stage-1"]


def first_push(commit: str) -> str:
    """GitHub time of the first run-branch push whose head contains commit."""
    for ev in RUN_EVENTS:
        if is_ancestor(commit, ev["after"]):
            return ev["timestamp"]
    return "not pushed"


def sha_text(s) -> str:
    if not isinstance(s, str):
        return "none"
    return "empty string" if s == "" else hashlib.sha256(s.encode("utf-8")).hexdigest()


def cell(r) -> str:
    return f"{r['case_id']}/{r['arm']}/{r['run']}"


lines = ["# Round-3 stage 1: generated tables", "",
         "Generated by `tools/round3_report.py` from files the papers and the operator checks already "
         "wrote; do not edit by hand. Nothing is re-scored here: a paper that ended INCOMPLETE has no "
         "score, and no ground truth is compared. Label of every run: human-authorized local PJU, NOT EC "
         "pool.", ""]

# 1. Papers.
lines += ["## Papers", "",
          "| Paper | Arm | Manifest sha256 | Status | Exam exit | Verify | Receipts | Seconds | Host clock (start, end) | Start record (push) | End record (push) |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
data = {}
for p in PAPERS:
    d = R3 / p / "run-1"
    run = json.loads((d / "RUN.json").read_text(encoding="utf-8"))
    rep = json.loads((d / "report.json").read_text(encoding="utf-8"))
    rec = [json.loads(l) for l in (d / "receipts.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    ver = (d / "verify.stdout.txt").read_text(encoding="utf-8").strip().splitlines()
    end = added_in(d / "RUN.json")
    arms = sorted({r["arm"] for r in rec})
    data[p] = (run, rep, rec, d)
    lines.append(f"| {p} | {', '.join(arms)} | `{run['manifest_sha256'][:12]}…` | **{run['status']}** | "
                 f"{run['exam_exit']} | {run['verify_exit']}: {ver[0] if ver else '(empty)'} | {len(rec)} | "
                 f"{run['seconds']} | {run['host_clock_utc']}, {run['host_clock_end_utc']} | "
                 f"`{run['start_commit'][:7]}` ({first_push(run['start_commit'])}) | "
                 f"`{end[:7]}` ({first_push(end)}) |")
lines += ["", "Exit codes (`gavel exam`): 0 PASS, 1 FAIL, 2 INVALID_PAPER / INVALID_RECORDS / INCOMPLETE "
          "or refused, 3 COMPLETE (scoring external). Verify is `gavel verify --content --results` as the "
          "runner ran it.", ""]

# 2. Cells without a valid attempt.
lines += ["## Cells without a valid attempt", "",
          "| Paper | Cell | Attempt | Reason (receipt) | raw_response sha256 | prompt_eval_count | eval_count | sum | done_reason |",
          "|---|---|---|---|---|---|---|---|---|"]
for p in PAPERS:
    run, rep, rec, d = data[p]
    for gap in rep["gaps"]["unresolved"]:
        key = "/".join(str(x) for x in gap["cell"])
        rows = [r for r in rec if cell(r) == key]
        for r in rows:
            g = r.get("generation") or {}
            pe, ev = g.get("prompt_eval_count"), g.get("eval_count")
            total = pe + ev if isinstance(pe, int) and isinstance(ev, int) else ""
            lines.append(f"| {p} | {key} | {r['attempt']} | {r.get('unaudited_reason')} | "
                         f"`{sha_text(r.get('raw_response'))[:16]}` | {pe} | {ev} | {total} | "
                         f"{g.get('done_reason')} |")
        sigs = {(sha_text(r.get("raw_response")), (r.get("generation") or {}).get("prompt_eval_count"),
                 (r.get("generation") or {}).get("eval_count"), (r.get("generation") or {}).get("done_reason"))
                for r in rows}
        same = len(sigs) == 1
        lines.append(f"| {p} | {key} | all {len(rows)} | identical raw_response sha256 and counts across "
                     f"attempts: **{'yes' if same else 'no'}** | | | | | |")
lines.append("")

# 3. K scored with gavel score-sealed.
sc = json.loads((R3 / "K" / "run-1" / "scoring" / "scoring.json").read_text(encoding="utf-8"))
lines += ["## Paper K, scored with `gavel score-sealed`", "",
          f"From `results/round-3/K/run-1/scoring/scoring.json` (status {sc['status']}, scored {sc['scored']}):", ""]
summary = sc["summary"]
if isinstance(summary, dict):
    for arm, s in summary.items():
        lines.append(f"- {arm}: `{json.dumps(s, ensure_ascii=False, sort_keys=True)}`")
else:
    for s in (summary if isinstance(summary, list) else [summary]):
        lines.append(f"- `{json.dumps(s, ensure_ascii=False, sort_keys=True)}`")
lines += ["", "K-fast ended INCOMPLETE and is not scored (`gavel score-sealed` never scores an INCOMPLETE "
          "paper).", ""]

# 4. Device placement per load.
lines += ["## Device placement of each model load", "",
          "| Paper | llama-server starts | Receipts | Distinct placements | Placement (offload line) |",
          "|---|---|---|---|---|"]
for p in PAPERS:
    run, rep, rec, d = data[p]
    t = (d / "ollama-load.txt").read_text(encoding="utf-8").splitlines()
    idx = [i for i, l in enumerate(t) if "starting llama-server" in l]
    blocks = [t[idx[k]:(idx[k + 1] if k + 1 < len(idx) else None)] for k in range(len(idx))]
    fits = {placement(b) for b in blocks}
    off = sorted({l for f in fits for l in f if "offloaded" in l})
    lines.append(f"| {p} | {len(blocks)} | {len(rec)} | {len(fits)} | {'; '.join(off)} |")
lines.append("")

# 5. Operator checks.
lines += ["## Operator checks", "",
          "`<paper>.txt` is the PREREG Addendum 6 (\"Papers\") check; `<paper>-load.txt` is the load check, "
          "not a PREREG step (`results/round-3/lock-check/loadcheck.py`).", "",
          "| File | Result | Added in | First pushed |", "|---|---|---|---|"]
for f in sorted((R3 / "lock-check").glob("*.txt")):
    res = [l for l in f.read_text(encoding="utf-8").splitlines() if l.startswith("Result:")]
    c = added_in(f)
    lines.append(f"| `{f.name}` | {res[0] if res else '(no result line)'} | `{c[:7]}` | {first_push(c)} |")
lines.append("")

# 6. First valid verdict of each cell, as written.
lines += ["## First valid verdict of each cell, as written (not scored)", ""]
for p in PAPERS:
    run, rep, rec, d = data[p]
    lines += [f"### {p}", "", "| Cell | Attempts | Verdict | mechanism_class | confidence |", "|---|---|---|---|---|"]
    order, by = [], {}
    for r in rec:
        k = cell(r)
        if k not in by:
            order.append(k)
            by[k] = []
        by[k].append(r)
    for k in order:
        valid = [r for r in by[k] if isinstance(r.get("verdict"), dict)]
        if valid:
            v = valid[0]["verdict"]
            lines.append(f"| {k} | {len(by[k])} | {v.get('verdict')} | {v.get('mechanism_class') or ''} | {v.get('confidence')} |")
        else:
            lines.append(f"| {k} | {len(by[k])} | no valid attempt | | |")
    lines.append("")

OUT.write_bytes(("\n".join(lines).rstrip("\n") + "\n").encode("utf-8"))
print(f"wrote {OUT.relative_to(ROOT).as_posix()} ({len(lines)} lines)")
sys.exit(0)
