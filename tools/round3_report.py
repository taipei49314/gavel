"""Generate results/round-3/TABLES.md from files the round-3 stage-1
papers and the operator checks already wrote (PREREG Addendum 4: tallies are
generated by a script, never written by hand).

    python -I -B tools/round3_report.py

Inputs:
- per paper, results/round-3/<paper>/run-1/{RUN.json, report.json,
  receipts.jsonl, verify.stdout.txt, ollama-load.txt}, and
  scoring/scoring.json where it exists;
- the paper manifests in cases/ (case tiers);
- the operator checks in results/round-3/lock-check/;
- the GitHub push events saved in results/round-3/push-events.json;
- git, for the commits that added each record and for the blobs at the
  commit R's lock check names (to print its values at full length);
- PREREG.md at the lock commit (Addendum 6's sha256 tables).

It imports nothing from gavel and scores nothing; it compares no ground
truth (the K section quotes `gavel score-sealed`'s own scoring). A paper
that ended INCOMPLETE has no score here. Standard library only.
"""

import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R3 = ROOT / "results" / "round-3"
PAPERS = ["R", "K", "R-fast", "K-fast"]
MANIFESTS = {"R": "cases/round-3-R.manifest.json", "K": "cases/round-3-K.manifest.json",
             "R-fast": "cases/round-3-R-fast.manifest.json",
             "K-fast": "cases/round-3-K-fast.manifest.json"}
HEADING = "## Addendum 6 (round-3 stage-1 lock"
OUT = R3 / "TABLES.md"

# Placement lines, as in results/round-3/lock-check/loadcheck.py.
PLACEMENT = [
    re.compile(r"cannot meet free memory target|will leave .* no changes needed"),
    re.compile(r"set ngl_per_device\[0\]\.\(n_layer, n_part, overflow_type\)="),
    re.compile(r"CUDA0 \(.*\): \d+ layers \(\d+ overflowing\)"),
    re.compile(r"offloaded \d+/\d+ layers to GPU"),
    re.compile(r"model buffer size"),
    re.compile(r"KV buffer size"),
]


def norm(line: str) -> str:
    line = re.sub(r"^time=\S+ ", "", line.rstrip("\r\n"))
    line = re.sub(r"--port \d+ ", "", line)
    line = re.sub(r"(\d+ layers \(\d+ overflowing\),\s+\d+ MiB used),\s+\d+ MiB free", r"\1", line)
    line = re.sub(r"need to reduce device memory by \d+ MiB", "need to reduce device memory by N MiB", line)
    return re.sub(r"will leave \d+ >=", "will leave N >=", line)


def placement(block):
    out = [norm(l) for l in block if any(p.search(l) for p in PLACEMENT)]
    sets = [l for l in out if "set ngl_per_device[0].(n_layer, n_part, overflow_type)=" in l]
    return tuple(l for l in out if l not in sets[:-1])


def git(*args, binary=False):
    done = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, check=True)
    return done.stdout if binary else done.stdout.decode("utf-8").strip()


def is_ancestor(a: str, b: str) -> bool:
    rc = subprocess.run(["git", "merge-base", "--is-ancestor", a, b], cwd=ROOT,
                        capture_output=True).returncode
    if rc not in (0, 1):
        raise SystemExit(f"git merge-base --is-ancestor {a} {b} failed (exit {rc})")
    return rc == 0


def added_in(path: Path) -> str:
    rel = path.relative_to(ROOT).as_posix()
    return git("log", "--diff-filter=A", "--format=%H", "-1", "--", rel)


EVENTS = json.loads((R3 / "push-events.json").read_text(encoding="utf-8"))
RUN_EVENTS = sorted(EVENTS["refs"]["refs/heads/round-3/run-stage-1"], key=lambda e: e["timestamp"])


def first_push(commit: str) -> str:
    """GitHub time of the earliest run-branch push whose head contains commit."""
    for ev in RUN_EVENTS:
        if is_ancestor(commit, ev["after"]):
            return ev["timestamp"]
    return "not pushed"


def sha_text(s) -> str:
    if not isinstance(s, str):
        return "none"
    return "empty string" if s == "" else hashlib.sha256(s.encode("utf-8")).hexdigest()


def cell(r) -> str:
    return f"{r['case_id']}/{r['arm']}/{r['run']}"


def valid(r) -> bool:
    return isinstance(r.get("verdict"), dict) and not r.get("unaudited_reason")


def canon(v) -> str:
    return json.dumps(v, sort_keys=True, ensure_ascii=False)


data = {}
for p in PAPERS:
    d = R3 / p / "run-1"
    run = json.loads((d / "RUN.json").read_text(encoding="utf-8"))
    rep = json.loads((d / "report.json").read_text(encoding="utf-8"))
    rec = [json.loads(l) for l in (d / "receipts.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    man = json.loads((ROOT / MANIFESTS[p]).read_text(encoding="utf-8"))
    data[p] = (run, rep, rec, d, man)
labels = sorted({data[p][0].get("label") for p in PAPERS})

lines = ["# Round-3 stage 1: generated tables", "",
         "Generated by `tools/round3_report.py` from the files listed in its docstring; do not edit by "
         "hand. The script scores nothing and compares no ground truth; the K section quotes "
         "`gavel score-sealed`'s own scoring. A paper that ended INCOMPLETE has no score here.",
         "", f"Run labels in RUN.json: {', '.join(repr(l) for l in labels)}.", ""]

# 1. Papers.
lines += ["## Papers", "",
          "| Paper | Arm | Manifest sha256 | Status | Exam exit | Verify | Receipts | Seconds | Host clock (start, end) | Start record (first push) | End record (first push) | Scoring file |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for p in PAPERS:
    run, rep, rec, d, man = data[p]
    ver = (d / "verify.stdout.txt").read_text(encoding="utf-8").strip().splitlines()
    end = added_in(d / "RUN.json")
    arms = sorted({r["arm"] for r in rec})
    scoring = d / "scoring" / "scoring.json"
    sc_note = "`scoring/scoring.json`" if scoring.is_file() else "none"
    lines.append(f"| {p} | {', '.join(arms)} | `{run['manifest_sha256'][:12]}…` | **{run['status']}** | "
                 f"{run['exam_exit']} | {run['verify_exit']}: {ver[0] if ver else '(empty)'} | {len(rec)} | "
                 f"{run['seconds']} | {run['host_clock_utc']}, {run['host_clock_end_utc']} | "
                 f"`{run['start_commit'][:7]}` ({first_push(run['start_commit'])}) | "
                 f"`{end[:7]}` ({first_push(end)}) | {sc_note} |")
lines += ["", "Fixed text, copied from `gavel/cli.py` (exit codes of `gavel exam`): \"0 PASS, 1 FAIL, "
          "2 INVALID_PAPER / INVALID_RECORDS / INCOMPLETE or refused (never scored), 3 COMPLETE (scoring "
          "is external; not a pass)\". \"Verify\" is the exit code and first output line of the "
          "`gavel verify` call the runner made (`verify.stdout.txt`).", ""]

# 2. Cells without a valid attempt, and cells without records.
lines += ["## Cells without a valid attempt", "",
          "| Paper | Cell | Attempt | Reason (receipt) | raw_response sha256 | Response length (characters) | prompt_eval_count | eval_count | Sum of the two | done_reason |",
          "|---|---|---|---|---|---|---|---|---|---|"]
missing_rows = []
for p in PAPERS:
    run, rep, rec, d, man = data[p]
    for m in rep["gaps"].get("missing", []):
        missing_rows.append(f"| {p} | {'/'.join(str(x) for x in (m if isinstance(m, list) else [m]))} |")
    for gap in rep["gaps"]["unresolved"]:
        key = "/".join(str(x) for x in gap["cell"])
        rows = [r for r in rec if cell(r) == key]
        for r in rows:
            g = r.get("generation") or {}
            pe, ev = g.get("prompt_eval_count"), g.get("eval_count")
            total = pe + ev if isinstance(pe, int) and isinstance(ev, int) else ""
            raw = r.get("raw_response")
            lines.append(f"| {p} | {key} | {r['attempt']} | {r.get('unaudited_reason')} | "
                         f"`{sha_text(raw)[:16]}` | {len(raw) if isinstance(raw, str) else ''} | {pe} | "
                         f"{ev} | {total} | {g.get('done_reason')} |")
        sigs = {(sha_text(r.get("raw_response")), (r.get("generation") or {}).get("prompt_eval_count"),
                 (r.get("generation") or {}).get("eval_count"), (r.get("generation") or {}).get("done_reason"))
                for r in rows}
        lines.append(f"| {p} | {key} | all {len(rows)} | identical raw_response sha256 and counts across "
                     f"attempts: **{'yes' if len(sigs) == 1 else 'no'}** | | | | | | |")
lines += ["", "Cells without records (`report.json`, `gaps.missing`): "
          + (", ".join(missing_rows) if missing_rows else "none in any paper") + ".", ""]

# 3. S-tier repeats (not a bar).
lines += ["## S-tier cases: the three runs compared (not a bar)", "",
          "Tiers are read from each paper's manifest. R is INCOMPLETE and was not scored, and R-fast is an "
          "observation paper, so this is not the S-reproducibility bar. \"Same verdict object\" compares the "
          "first valid verdict of each run as canonical JSON (sorted keys).", "",
          "| Paper | Case | Runs | Same verdict object | Same raw_response sha256 | Verdict, mechanism_class |",
          "|---|---|---|---|---|---|"]
for p in PAPERS:
    run, rep, rec, d, man = data[p]
    s_cases = [c["case_id"] for c in man["cases"] if c.get("tier") == "S"]
    for cid in s_cases:
        per_run = {}
        for r in rec:
            if r["case_id"] == cid and valid(r) and r["run"] not in per_run:
                per_run[r["run"]] = r
        vs = {canon(r["verdict"]) for r in per_run.values()}
        raws = {sha_text(r.get("raw_response")) for r in per_run.values()}
        first = per_run[min(per_run)]["verdict"] if per_run else {}
        lines.append(f"| {p} | {cid} | {sorted(per_run)} | {'yes' if len(vs) == 1 else 'no'} | "
                     f"{'yes' if len(raws) == 1 else 'no'} | {first.get('verdict')}, {first.get('mechanism_class') or ''} |")
lines.append("")

# 4. K scored with gavel score-sealed.
lines += ["## Scored papers (`gavel score-sealed`)", ""]
for p in PAPERS:
    run, rep, rec, d, man = data[p]
    f = d / "scoring" / "scoring.json"
    if not f.is_file():
        lines.append(f"- {p}: no scoring file (status {run['status']}, manifest scoring "
                     f"{json.dumps(man.get('scoring'))}).")
        continue
    sc = json.loads(f.read_text(encoding="utf-8"))
    lines.append(f"- {p}: `{f.relative_to(ROOT).as_posix()}`, status {sc['status']}, scored "
                 f"{json.dumps(sc['scored'])}.")
    summary = sc["summary"]
    items = summary.items() if isinstance(summary, dict) else enumerate(summary if isinstance(summary, list) else [summary])
    for arm, s in items:
        lines.append(f"  - {arm}: `{json.dumps(s, ensure_ascii=False, sort_keys=True)}`")
lines.append("")

# 5. Device placement per load, within and across papers.
lines += ["## Device placement of each model load", "",
          "| Paper | Arm | llama-server starts | Receipts | Distinct placements in the paper | Offload line |",
          "|---|---|---|---|---|---|"]
by_arm = {}
for p in PAPERS:
    run, rep, rec, d, man = data[p]
    arm = ", ".join(sorted({r["arm"] for r in rec}))
    t = (d / "ollama-load.txt").read_text(encoding="utf-8").splitlines()
    idx = [i for i, l in enumerate(t) if "starting llama-server" in l]
    blocks = [t[idx[k]:(idx[k + 1] if k + 1 < len(idx) else None)] for k in range(len(idx))]
    fits = {placement(b) for b in blocks}
    by_arm.setdefault(arm, set()).update(fits)
    off = sorted({l for f in fits for l in f if "offloaded" in l})
    lines.append(f"| {p} | {arm} | {len(blocks)} | {len(rec)} | {len(fits)} | {'; '.join(off)} |")
lines += ["", "Across papers of the same arm:", ""]
for arm, fits in sorted(by_arm.items()):
    lines.append(f"- {arm}: {len(fits)} distinct placement(s) over all its papers' loads.")
    for f in sorted(fits):
        for l in f:
            lines.append(f"  - `{l}`")
lines.append("")

# 6. Operator checks.
lines += ["## Operator checks", "",
          "Fixed text: `<paper>.txt` is the PREREG Addendum 6 (\"Papers\") check; `<paper>-load.txt` is "
          "the load check, not a PREREG step (`results/round-3/lock-check/loadcheck.py`).", "",
          "| File | Result | Added in | First pushed |", "|---|---|---|---|"]
for f in sorted((R3 / "lock-check").glob("*.txt")):
    res = [l for l in f.read_text(encoding="utf-8").splitlines() if l.startswith("Result:")]
    c = added_in(f)
    lines.append(f"| `{f.name}` | {res[0] if res else '(no result line)'} | `{c[:7]}` | {first_push(c)} |")
lines.append("")

# 7. R's lock check at full length.
rtxt = (R3 / "lock-check" / "R.txt").read_text(encoding="utf-8")
head_m = re.search(r"HEAD ([0-9a-f]{40})", rtxt)
lock_m = re.search(r"lock commit ([0-9a-f]{40})", rtxt)
r_head, lock = head_m.group(1), lock_m.group(1)
prereg = git("show", f"{lock}:PREREG.md")
add6 = prereg[prereg.index(HEADING):]
want = re.findall(r"^  \| `([^`]+)` \| `([0-9a-f]{64})` \|$", add6, re.M)
am = re.search(r"`approved-models\.json` sha256 `([0-9a-f]{64})`", add6)
want.append(("approved-models.json", am.group(1)))
want += [(path, sha) for _, path, sha in re.findall(r"^  \| (R|K|R-fast|K-fast) \| `([^`]+)` \| `([0-9a-f]{64})` \|", add6, re.M)]
lines += ["## The values behind `lock-check/R.txt`, at full length", "",
          f"`R.txt` printed 12-character prefixes. Below, each file's blob at the commit `R.txt` names as HEAD "
          f"(`{r_head[:7]}`), hashed here, against the value in Addendum 6 at the lock commit (`{lock[:7]}`).", "",
          "| File | Addendum 6 sha256 | Blob sha256 at R.txt's HEAD | Equal |", "|---|---|---|---|"]
for path, w in want:
    got = hashlib.sha256(git("show", f"{r_head}:{path}", binary=True)).hexdigest()
    lines.append(f"| `{path}` | `{w}` | `{got}` | {'yes' if got == w else '**no**'} |")
lines.append("")

# 8. First valid verdict of each cell, as written.
lines += ["## First valid verdict of each cell, as written (not scored)", ""]
for p in PAPERS:
    run, rep, rec, d, man = data[p]
    tiers = {c["case_id"]: c.get("tier") for c in man["cases"]}
    lines += [f"### {p}", "", "| Cell | Tier | Attempts | Verdict | mechanism_class | confidence |",
              "|---|---|---|---|---|---|"]
    order, by = [], {}
    for r in rec:
        k = cell(r)
        if k not in by:
            order.append(k)
            by[k] = []
        by[k].append(r)
    for k in order:
        ok = [r for r in by[k] if valid(r)]
        t = tiers.get(by[k][0]["case_id"]) or ""
        if ok:
            v = ok[0]["verdict"]
            lines.append(f"| {k} | {t} | {len(by[k])} | {v.get('verdict')} | {v.get('mechanism_class') or ''} | {v.get('confidence')} |")
        else:
            lines.append(f"| {k} | {t} | {len(by[k])} | no valid attempt | | |")
    lines.append("")

OUT.write_bytes(("\n".join(lines).rstrip("\n") + "\n").encode("utf-8"))
print(f"wrote {OUT.relative_to(ROOT).as_posix()} ({len(lines)} lines)")
sys.exit(0)
