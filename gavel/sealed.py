"""Sealed-paper scoring after reveal (PREREG Addendum 5), generated from data.

Addendum 5 fixes the scoring formula of a sealed paper: 「attack-真相卷須
verdict=attack（inconclusive 計 miss）；clean-真相卷須 verdict=clean」, and asks
to 「另報 inconclusive 率」. Addendum 4 requires reconciliation tables to be
generated by script, never written by hand. This module is that script:

- The paper is a locked manifest with scoring "external" and one run per case
  and arm. The answer key is read from bytes: the SEALED-PREREG.md format
  (parse_answer_key_markdown) or a JSON key (parse_answer_key_json).
- Records are resolved by the attempt rule of gavel.qualify (first valid
  attempt within the cap); there is no last-record-wins. Every re-attempted
  cell is disclosed.
- Completeness comes first (Addendum 4: 「缺件/UNAUDITED/題數漂移 →
  INCOMPLETE，永不計分」). Only a COMPLETE paper is scored. An INCOMPLETE paper
  gets an observation table without correctness marks or totals; a paper
  with invalid records or manifest gets only its errors.
- Per arm: correct/total under the Addendum 5 rule (total is every case of
  the paper), misses, the inconclusive rate, the mechanism match rate over
  attack-truth cases, and pair discrimination (a pair is discriminated by an
  arm when the arm is correct on both members).
- Every table cell and summary line is computed from the inputs; the output
  is deterministic and carries the sha256 of every input file.
- This module reports scores. It does not decide PASS; the round's PREREG
  does.
"""

import hashlib
import json
import re
from pathlib import Path

from . import __version__
from .judge import strict_loads
from .qualify import evaluate, resolve_attempts, runs_for

KEY_VERDICTS = ("attack", "clean")
SCORE_OUTPUTS = ("scoring.md", "scoring.json")
RULE = ("PREREG Addendum 5: an attack-truth case is correct only with verdict attack "
        "(inconclusive is a miss); a clean-truth case is correct only with verdict clean; "
        "the inconclusive rate is reported. Each case counts once per arm, at its first "
        "valid attempt within the attempt cap.")


class AnswerKeyError(ValueError):
    """The answer key cannot be read, or it does not fit the paper."""


# --- answer keys ------------------------------------------------------------------

_PAIR_LINE = re.compile(r"^- (P\d+): (\S+) / (\S+)\s*$", re.M)
_VERDICT_LINE = re.compile(r"^- TRUE expected verdict: (\S+)\s*$", re.M)
_MECHANISM_LINE = re.compile(r"^- Expected mechanism_class: `([^`]*)`", re.M)
_CATEGORY_PAIR = re.compile(r"^- Category: (P\d+):", re.M)


def parse_answer_key_markdown(text: str) -> dict:
    """Read a SEALED-PREREG.md answer key.

    Pairs come from lines "- P1: SP-001 / SP-008". Each case is a "### <id>"
    section holding exactly one "- TRUE expected verdict: <v>" line and one
    "- Expected mechanism_class: `<class>`" line (`""` means empty). A
    "- Category: P<n>: ..." line must name the pair the case is in.
    """
    pairs = {}
    for label, first, second in _PAIR_LINE.findall(text):
        if label in pairs:
            raise AnswerKeyError(f"pair {label} is listed twice")
        pairs[label] = [first, second]
    cases, categories = {}, {}
    for section in re.split(r"^### ", text, flags=re.M)[1:]:
        heading, _, body = section.partition("\n")
        cid = heading.strip()
        verdicts = _VERDICT_LINE.findall(body)
        if not verdicts:
            continue  # not a case section
        if len(verdicts) != 1:
            raise AnswerKeyError(f"{cid}: {len(verdicts)} 'TRUE expected verdict' lines")
        mechanisms = _MECHANISM_LINE.findall(body)
        if len(mechanisms) != 1:
            raise AnswerKeyError(f"{cid}: needs exactly one 'Expected mechanism_class' line")
        if cid in cases:
            raise AnswerKeyError(f"{cid}: listed twice")
        mechanism = "" if mechanisms[0] == '""' else mechanisms[0]
        cases[cid] = {"verdict": verdicts[0], "mechanism_class": mechanism}
        category = _CATEGORY_PAIR.findall(body)
        if category:
            categories[cid] = category[0]
    key = _finish_key(cases, pairs)
    for cid, label in categories.items():
        if key["cases"][cid]["pair"] != label:
            raise AnswerKeyError(f"{cid}: its category names pair {label}, the pair list "
                                 f"puts it in {key['cases'][cid]['pair']}")
    return key


def parse_answer_key_json(data) -> dict:
    """Read a JSON answer key: {"key_version": 1, "cases": {case_id:
    {"verdict", "mechanism_class", "pair": label or null}}}."""
    if not isinstance(data, dict) or data.get("key_version") != 1 \
            or not isinstance(data.get("cases"), dict) or set(data) - {"key_version", "cases"}:
        raise AnswerKeyError("a JSON answer key is {'key_version': 1, 'cases': {...}}")
    cases, pairs = {}, {}
    for cid, entry in data["cases"].items():
        if not isinstance(entry, dict) or set(entry) != {"verdict", "mechanism_class", "pair"}:
            raise AnswerKeyError(f"{cid}: needs exactly verdict, mechanism_class and pair")
        cases[cid] = {"verdict": entry["verdict"], "mechanism_class": entry["mechanism_class"]}
        if entry["pair"] is not None:
            if not isinstance(entry["pair"], str) or not entry["pair"]:
                raise AnswerKeyError(f"{cid}: pair must be a non-empty string or null")
            pairs.setdefault(entry["pair"], []).append(cid)
    return _finish_key(cases, pairs)


def _finish_key(cases: dict, pairs: dict) -> dict:
    if not cases:
        raise AnswerKeyError("the answer key holds no cases")
    for cid, entry in cases.items():
        if entry["verdict"] not in KEY_VERDICTS:
            raise AnswerKeyError(f"{cid}: expected verdict {entry['verdict']!r} is not one of "
                                 f"{KEY_VERDICTS} (the Addendum 5 rule scores only these)")
        mechanism = entry["mechanism_class"]
        if not isinstance(mechanism, str):
            raise AnswerKeyError(f"{cid}: mechanism_class must be text")
        if (entry["verdict"] == "attack") != bool(mechanism):
            raise AnswerKeyError(f"{cid}: an attack truth needs a mechanism_class and a "
                                 f"clean truth must have none")
        entry["pair"] = None
    for label, members in pairs.items():
        if len(members) != 2 or members[0] == members[1]:
            raise AnswerKeyError(f"pair {label} must have two different members: {members}")
        for cid in members:
            if cid not in cases:
                raise AnswerKeyError(f"pair {label} names {cid}, which has no expected verdict")
            if cases[cid]["pair"] is not None:
                raise AnswerKeyError(f"{cid} is in pairs {cases[cid]['pair']} and {label}")
            cases[cid]["pair"] = label
    return {"cases": cases, "pairs": pairs}


def load_answer_key(path) -> dict:
    """Load an answer key file (.json, read with judge.strict_loads; otherwise
    the SEALED-PREREG.md format). Adds "file" (the name) and "sha256" (of the
    bytes)."""
    path = Path(path)
    try:
        raw = path.read_bytes()
        text = raw.decode("utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise AnswerKeyError(f"answer key unreadable: {path.name}: {type(exc).__name__}") from exc
    if path.suffix.lower() == ".json":
        try:
            key = parse_answer_key_json(strict_loads(text))
        except ValueError as exc:
            if isinstance(exc, AnswerKeyError):
                raise
            raise AnswerKeyError(f"answer key is not valid JSON (duplicate keys and "
                                 f"NaN/Infinity are refused): {path.name}: {exc}") from exc
    else:
        key = parse_answer_key_markdown(text)
    key["file"] = path.name
    key["sha256"] = hashlib.sha256(raw).hexdigest()
    return key


# --- scoring ------------------------------------------------------------------------

def check_key_fits(manifest: dict, key: dict) -> list[str]:
    """Every reason the key cannot score this (valid) paper manifest."""
    problems = []
    if manifest.get("scoring") != "external":
        problems.append("score-sealed scores only a paper with scoring 'external'")
    for arm, spec in manifest["arms"].items():
        for case in manifest["cases"]:
            if runs_for(spec, case["tier"]) != 1:
                problems.append(f"arm {arm} has more than one run on {case['case_id']}; the "
                                f"Addendum 5 rule scores one verdict per case and arm")
                break
    ids = [case["case_id"] for case in manifest["cases"]]
    missing = [cid for cid in ids if cid not in key["cases"]]
    extra = sorted(set(key["cases"]) - set(ids))
    if missing:
        problems.append(f"the answer key has no expected verdict for {missing}")
    if extra:
        problems.append(f"the answer key names cases outside the paper: {extra}")
    return problems


def arm_order(manifest: dict) -> list[str]:
    gating = manifest["gating_arm"]
    return [gating] + [arm for arm in manifest["arms"] if arm != gating]


def _verdict_cell(record) -> dict | None:
    if record is None:
        return None
    judged = record["verdict"]
    return {"verdict": judged.get("verdict"), "mechanism_class": judged.get("mechanism_class", ""),
            "attempt": record["attempt"]}


def _arm_summary(arm: str, rows: list, pairs: dict) -> dict:
    ids = [row["case_id"] for row in rows]
    correct = [row["case_id"] for row in rows if row["verdicts"][arm]["correct"]]
    inconclusive = [row["case_id"] for row in rows
                    if row["verdicts"][arm]["verdict"] == "inconclusive"]
    attack_truth = [row for row in rows if row["truth"] == "attack"]
    matched = [row["case_id"] for row in attack_truth
               if row["verdicts"][arm]["verdict"] == "attack"
               and row["verdicts"][arm]["mechanism_class"] == row["expected_mechanism"]]
    discriminated = [label for label, members in pairs.items()
                     if all(cid in correct for cid in members)]
    return {
        "correct": len(correct), "total": len(ids),
        "misses": [cid for cid in ids if cid not in correct],
        "all_correct": len(correct) == len(ids),
        "inconclusive": len(inconclusive), "inconclusive_cases": inconclusive,
        "mechanism_match": len(matched), "attack_truth": len(attack_truth),
        "mechanism_mismatches": [row["case_id"] for row in attack_truth
                                 if row["case_id"] not in matched],
        "pairs_discriminated": discriminated, "pairs_total": len(pairs),
        "pairs_not_discriminated": [label for label in pairs if label not in discriminated],
    }


def score_sealed(manifest: dict, key: dict, records: list[dict]) -> dict:
    """Score a sealed paper's records against its answer key.

    The manifest must be valid (load_paper). Raises AnswerKeyError when the
    key does not fit the paper. Returns the score dict that render_markdown
    and the scoring.json output are made from; "scored" is true only for a
    COMPLETE paper.
    """
    problems = check_key_fits(manifest, key)
    if problems:
        raise AnswerKeyError("; ".join(problems))
    report = evaluate(manifest, records)
    arms = arm_order(manifest)
    score = {
        "paper_id": manifest["paper_id"],
        "status": report["status"],
        "scored": report["status"] == "COMPLETE",
        "rule": RULE,
        "arms": arms,
        "pairs": {label: list(members) for label, members in key["pairs"].items()},
        "errors": report["errors"],
        "gaps": report["gaps"],
        "reattempted": report["reattempted"],
        "attempt_cap": manifest["attempt_cap"],
        "cases": [],
        "summary": {},
    }
    if report["status"] not in ("COMPLETE", "INCOMPLETE"):
        return score
    resolved = resolve_attempts(manifest, records)["resolved"]
    for case in manifest["cases"]:
        cid = case["case_id"]
        truth = key["cases"][cid]
        row = {"case_id": cid, "truth": truth["verdict"],
               "expected_mechanism": truth["mechanism_class"], "pair": truth["pair"],
               "verdicts": {}}
        for arm in arms:
            cell = _verdict_cell(resolved.get((cid, arm, 1)))
            if cell is not None and score["scored"]:
                cell["correct"] = cell["verdict"] == truth["verdict"]
            row["verdicts"][arm] = cell
        score["cases"].append(row)
    if score["scored"]:
        score["summary"] = {arm: _arm_summary(arm, score["cases"], key["pairs"])
                            for arm in arms}
    return score


# --- output -----------------------------------------------------------------------------

def _pct(part: int, whole: int) -> str:
    return f"{100 * part / whole:.1f}%" if whole else "n/a"


def _names(items) -> str:
    return ", ".join(items) if items else "none"


def summary_lines(score: dict) -> list[str]:
    """The per-arm summary lines, computed from the score."""
    lines = []
    for arm in score["arms"]:
        s = score["summary"].get(arm)
        if s is None:
            continue
        lines.append(
            f"{arm}: correct {s['correct']}/{s['total']} (misses: {_names(s['misses'])}); "
            f"inconclusive {s['inconclusive']}/{s['total']} ({_pct(s['inconclusive'], s['total'])}); "
            f"mechanism match {s['mechanism_match']}/{s['attack_truth']} attack-truth cases "
            f"({_pct(s['mechanism_match'], s['attack_truth'])}; mismatched: "
            f"{_names(s['mechanism_mismatches'])}); pairs discriminated "
            f"{len(s['pairs_discriminated'])}/{s['pairs_total']} "
            f"({_names(s['pairs_discriminated'])})")
    return lines


def _status_line(score: dict) -> str:
    status = score["status"]
    if status == "COMPLETE":
        return (f"status: COMPLETE; every cell resolved to its first valid attempt within "
                f"the cap {score['attempt_cap']}; scored")
    if status == "INCOMPLETE":
        return (f"status: INCOMPLETE ({len(score['gaps']['missing'])} cell(s) without "
                f"records, {len(score['gaps']['unresolved'])} without a valid attempt within "
                f"the cap {score['attempt_cap']}); an incomplete paper is never scored, so "
                f"the table lists resolved verdicts as observations only, without "
                f"correctness marks or totals")
    return f"status: {status}; not scored, no table"


def _cell_text(cell, scored: bool) -> str:
    if cell is None:
        return "no valid verdict"
    text = cell["verdict"] or "?"
    if cell["verdict"] == "attack":
        text += f" ({cell['mechanism_class']})"
    if scored and not cell["correct"]:
        text += " ✗"
    return text


def render_markdown(score: dict, provenance: dict) -> str:
    """scoring.md: provenance, status, the table and the summary lines."""
    scored = score["scored"]
    title = "Sealed paper scoring" if scored else "Sealed paper observations (not scored)"
    out = [f"# {title}: {score['paper_id']}", "",
           f"Generated by `gavel score-sealed` (harness {provenance['harness_version']}). "
           f"Every cell and summary line below is computed from these inputs:", "",
           f"- manifest: {provenance['manifest_file']}, sha256 {provenance['manifest_sha256']}",
           f"- answer key: {provenance['key_file']}, sha256 {provenance['key_sha256']}",
           f"- receipts: {provenance['receipts_file']}, sha256 {provenance['receipts_sha256']}, "
           f"{provenance['receipts_count']} receipt(s), receipt v{provenance['receipt_version']}, "
           f"last receipt_id {provenance['receipts_head']}",
           f"- rule: {score['rule']}",
           f"- {_status_line(score)}", ""]
    if score["errors"]:
        out += ["## Errors", ""] + [f"- {error}" for error in score["errors"]] + [""]
    if score["cases"]:
        arms = score["arms"]
        out += ["| case | truth | " + " | ".join(arms) + " | pair |",
                "|---|---|" + "---|" * len(arms) + "---|"]
        for row in score["cases"]:
            truth = row["truth"] + (f" ({row['expected_mechanism']})"
                                    if row["expected_mechanism"] else "")
            cells = [_cell_text(row["verdicts"][arm], scored) for arm in arms]
            out.append(f"| {row['case_id']} | {truth} | " + " | ".join(cells)
                       + f" | {row['pair'] or 'control'} |")
        out.append("")
    if scored:
        out += ["## Per arm", ""] + [f"- {line}" for line in summary_lines(score)] + [""]
    gaps = score["gaps"]["unresolved"]
    missing = score["gaps"]["missing"]
    if gaps or missing:
        out += ["## Cells without a valid verdict", ""]
        out += [f"- {cell[1]} {cell[0]} run {cell[2]}: no record" for cell in missing]
        out += [f"- {gap['cell'][1]} {gap['cell'][0]} run {gap['cell'][2]}: "
                f"{gap['attempts']} attempt(s), cap {gap['cap']}; reasons: "
                f"{'; '.join(str(r) for r in gap['unaudited_reasons'])}" for gap in gaps]
        out.append("")
    out += ["## Re-attempted cells", ""]
    if score["reattempted"]:
        out += [f"- {item['cell'][1]} {item['cell'][0]} run {item['cell'][2]}: "
                f"{item['attempts']} attempts, attempt {item['counted_attempt']} counted; "
                f"earlier reasons: {'; '.join(str(r) for r in item['unaudited_reasons'])}"
                for item in score["reattempted"]]
    else:
        out.append("- none")
    return "\n".join(out) + "\n"


def write_outputs(out_dir, score: dict, provenance: dict) -> list[Path]:
    """Write scoring.md and scoring.json once; refuse to overwrite either."""
    out = Path(out_dir)
    taken = [name for name in SCORE_OUTPUTS if (out / name).exists()]
    if taken:
        raise FileExistsError(f"{out.name} already holds {', '.join(taken)}; scoring "
                              f"outputs are written once")
    out.mkdir(parents=True, exist_ok=True)
    document = {"provenance": provenance, **score}
    paths = [out / "scoring.json", out / "scoring.md"]
    paths[0].write_text(json.dumps(document, sort_keys=True, indent=2, ensure_ascii=False) + "\n",
                        encoding="utf-8", newline="\n")
    paths[1].write_text(render_markdown(score, provenance), encoding="utf-8", newline="\n")
    return paths


def provenance_for(manifest_path, paper: dict, key: dict, receipts_path,
                   receipts: list[dict]) -> dict:
    """File names and hashes of every input (names only, never local paths)."""
    receipts_path = Path(receipts_path)
    return {
        "harness_version": __version__,
        "manifest_file": Path(manifest_path).name,
        "manifest_sha256": paper["manifest_sha256"],
        "key_file": key["file"],
        "key_sha256": key["sha256"],
        "receipts_file": receipts_path.name,
        "receipts_sha256": hashlib.sha256(receipts_path.read_bytes()).hexdigest(),
        "receipts_count": len(receipts),
        "receipt_version": receipts[0]["receipt_version"] if receipts else None,
        "receipts_head": receipts[-1]["receipt_id"] if receipts else None,
    }
